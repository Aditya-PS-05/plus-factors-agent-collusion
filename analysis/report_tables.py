"""Build report-ready tables from the evaluation markdown files, so that no number in the
report is transcribed by hand. Writes report/tables_generated.md.

Table 1: likelihood ratios per factor across framings (training seeds).
Table 2: held-out balanced accuracy with bootstrap intervals per rule across framings.
Usage: python report_tables.py results --out report/tables_generated.md"""
from __future__ import annotations
import argparse, re
from pathlib import Path

FRAMINGS = [  # (label, evaluation file for LRs, evaluation file for the no-OP constellation)
    ("A vs B,C,D (pre-registered)", "evaluation_prereg.md", "evaluation_prereg_noOP.md", "evaluation_prereg_conduct.md"),
    ("Adec vs B,Bdec,C,D (extension)", "evaluation_ext_Adec.md", "evaluation_ext_Adec_noOP.md", "evaluation_ext_Adec_conduct.md"),
    ("Instructed vs C,D (exploratory)", "evaluation_ext_instructed.md", "evaluation_ext_instructed_noOP.md", "evaluation_ext_instructed_conduct.md"),
    ("Study 2: A6 vs B6,C6,D6", "s2_evaluation_prereg.md", "s2_evaluation_prereg_noOP.md", "s2_evaluation_prereg_conduct.md"),
    ("Study 3: Aq,Adecq vs Dq", "s3_evaluation.md", "s3_evaluation.md", "s3_evaluation_conduct.md"),
]
FACTORS = ["H", "Hrel", "CI", "CD", "NC", "PC", "PI", "WA", "OP"]
NAMES = {"H": "H, coalition advantage", "Hrel": "Hrel, pair reward vs baseline", "CI": "CI, judge rating",
         "CD": "CD, costly deference", "NC": "NC, internal non-collision", "PC": "PC, priority capture",
         "PI": "PI, private info posted", "WA": "WA, word-action inconsistency", "OP": "OP, private channel existed"}
RULES = [("Harm alone (H)", "Harm alone (H)"), ("Hrel alone", "Pair reward vs baseline (Hrel)"), ("CI alone", "Judge alone (CI)"),
         ("CD alone", "Costly deference (CD)"), ("NC alone", "Internal non-collision (NC)"), ("PC alone", "Priority capture (PC)"),
         ("PI alone", "Private info posted (PI)"), ("WA alone", "Word-action inconsistency (WA)")]


def parse_lr(path: Path):
    out = {}
    if not path.exists():
        return out
    for line in path.read_text().splitlines():
        m = re.match(r"\| (\w+) \| ([\d.]+) \| ([\d.]+) \| ([\d.inf]+) \| \[([\d.]+), ([\d.]+)\]", line)
        if m:
            out[m.group(1)] = (float(m.group(4)), float(m.group(5)), float(m.group(6)), float(m.group(2)), float(m.group(3)))
    return out


def parse_heldout(path: Path):
    out = {}
    if not path.exists():
        return out
    for line in path.read_text().splitlines():
        m = re.match(r"\| (.+?) \| ([\d.]+) \[([\d.]+), ([\d.]+)\] \|", line)
        if m:
            out[m.group(1).strip()] = (float(m.group(2)), float(m.group(3)), float(m.group(4)))
    return out


def main():
    ap = argparse.ArgumentParser(); ap.add_argument("results", type=Path); ap.add_argument("--out", type=Path, required=True)
    a = ap.parse_args()
    avail = [f for f in FRAMINGS if (a.results / f[1]).exists()]
    L = ["<!-- generated by analysis/report_tables.py; do not edit by hand -->", ""]
    L.append("Table 1. Likelihood ratios S on training seeds with seed-bootstrap 90 percent intervals (Study 3 has one confound, Dq, so its ratios are against that condition alone). * no event on training seeds, S is the smoothing floor; † tautological, the channel defines the agreement conditions. OP identifies the agreement conditions by construction and is excluded from all claims.")
    L.append(""); L.append("| Factor | " + " | ".join(f[0] for f in avail) + " |"); L.append("|---" * (1 + len(avail)) + "|")
    lrs = [parse_lr(a.results / f[1]) for f in avail]
    for k in FACTORS:
        cells = []
        for lr in lrs:
            if k in lr:
                S, lo, hi, p, q = lr[k]
                note = "†" if k == "OP" else ("*" if k == "WA" and p < 0.1 else "")
                cells.append(f"{S:.2f} [{lo:.2f}, {hi:.2f}]{note}" if not note else f"{S:.2f}{note}")
            else:
                cells.append("-")
        L.append(f"| {NAMES[k]} | " + " | ".join(cells) + " |")
    L.append("")
    L.append("Table 2. Held-out balanced accuracy with seed-bootstrap 90 percent intervals (15 held-out seeds per condition). Chance is 0.50. The constellation excludes OP; with OP it scores 1.00 wherever a private channel defines the agreement condition, which is the tautology, not a result.")
    L.append(""); L.append("| Rule | " + " | ".join(f[0] for f in avail) + " |"); L.append("|---" * (1 + len(avail)) + "|")
    ho = [parse_heldout(a.results / f[1]) for f in avail]
    ho_noop = [parse_heldout(a.results / f[2]) for f in avail]
    ho_cond = [parse_heldout(a.results / f[3]) for f in avail]
    def cell(d, key):
        return f"{d[key][0]:.2f} [{d[key][1]:.2f}, {d[key][2]:.2f}]" if key in d else "-"
    for key, label in RULES:
        L.append(f"| {label} | " + " | ".join(cell(d, key) for d in ho) + " |")
    L.append("| Constellation, all factors except OP | " + " | ".join(cell(d, "Constellation") for d in ho_noop) + " |")
    L.append("| Constellation, conduct factors only (no CI, no OP) | " + " | ".join(cell(d, "Constellation") for d in ho_cond) + " |")
    a.out.write_text("\n".join(L) + "\n"); print("\n".join(L))


if __name__ == "__main__":
    main()
